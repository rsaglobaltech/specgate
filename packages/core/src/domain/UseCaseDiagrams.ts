/**
 * The use-case diagram and each use case's activity diagram, generated — never
 * hand-kept (REQ-634, #544). From `docs/specs/use-cases.md` and each
 * `docs/specs/use-cases/UC-NNN.md`:
 *
 * - `docs/specs/use-case-diagrams.md`, in Mermaid, which GitHub, GitLab and
 *   the studio render without a server, as `actors.md` is;
 * - `docs/specs/use-cases.puml`, the same diagrams in PlantUML, for a team
 *   that draws with it.
 *
 * Pure: sources in, text out, the same bytes for the same sources.
 */
import type { UseCaseRow } from "./UseCaseDelta";
import type { UseCaseSpec } from "./UseCaseSpec";

const ident = (s: string) => s.replace(/[^A-Za-z0-9_]/g, "_");
const quote = (s: string) => s.replace(/"/g, "'");
const byId = <T extends { id: string }>(xs: readonly T[]) =>
  [...xs].sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));

const HEADER = [
  "<!-- Generated by specgate from docs/specs/use-cases.md and docs/specs/use-cases/UC-NNN.md.",
  "     Do not edit: `specgate check` rewrites it, and `validate` reports a copy that differs. -->",
];

/** The catalog as a Mermaid flowchart: each actor linked to the use cases it achieves. */
export function useCaseChart(cases: readonly UseCaseRow[]): string[] {
  const actors = [...new Set(cases.map((c) => c.actor).filter(Boolean))].sort();
  const fc = ["flowchart LR"];
  for (const a of actors) fc.push(`  actor_${ident(a)}(["${quote(a)}"])`);
  fc.push("  subgraph system [System]");
  for (const c of byId(cases)) fc.push(`    ${ident(c.id)}("${c.id} — ${quote(c.name)}")`);
  fc.push("  end");
  for (const c of byId(cases)) if (c.actor) fc.push(`  actor_${ident(c.actor)} --- ${ident(c.id)}`);
  return fc;
}

/** A use case's flows as a Mermaid flowchart: the main flow down, each alternative branching at its step. */
export function activityChart(spec: UseCaseSpec): string[] {
  const main = spec.flows.find((f) => f.id === "main");
  const fc = ["flowchart TD", "  start((start))"];
  const steps = main?.steps ?? [];
  steps.forEach((s, i) => fc.push(`  m${i + 1}["${i + 1}. ${quote(s)}"]`));
  fc.push("  finish((end))");
  const chain = ["start", ...steps.map((_, i) => `m${i + 1}`), "finish"];
  for (let i = 0; i + 1 < chain.length; i += 1) {
    const label =
      i === 0 && main?.scenarios.length ? ` -- ${main.scenarios.join(", ")} -->` : " -->";
    fc.push(`  ${chain[i]}${label} ${chain[i + 1]}`);
  }
  for (const f of spec.flows.filter((x) => x.id !== "main")) {
    const from = f.atStep && f.atStep <= steps.length ? `m${f.atStep}` : "start";
    const ids = f.steps.map((_, i) => `${ident(f.id)}_${i + 1}`);
    f.steps.forEach((s, i) => fc.push(`  ${ids[i]}["${f.id}.${i + 1} ${quote(s)}"]`));
    const label = `${f.id}: ${quote(f.title)}${f.scenarios.length ? ` (${f.scenarios.join(", ")})` : ""}`;
    if (ids.length) {
      fc.push(`  ${from} -. "${label}" .-> ${ids[0]}`);
      for (let i = 0; i + 1 < ids.length; i += 1) fc.push(`  ${ids[i]} --> ${ids[i + 1]}`);
      fc.push(`  ${ids[ids.length - 1]} --> finish`);
    }
  }
  return fc;
}

/** `docs/specs/use-case-diagrams.md`, or null when the catalog has no use case of its own. */
export function renderUseCaseDiagrams(
  cases: readonly UseCaseRow[],
  specs: readonly UseCaseSpec[]
): string | null {
  if (cases.length === 0) return null;
  const out = [
    "# Use case diagrams",
    "",
    ...HEADER,
    "",
    "## Use cases",
    "",
    "```mermaid",
    ...useCaseChart(cases),
    "```",
    "",
  ];
  const known = new Set(cases.map((c) => c.id));
  for (const s of byId(specs.filter((x) => known.has(x.id)))) {
    out.push(`## ${s.id} — ${s.name}`, "", "```mermaid", ...activityChart(s), "```", "");
  }
  return out.join("\n");
}

/** `docs/specs/use-cases.puml`: the same diagrams in PlantUML, or null with no use case. */
export function renderUseCasesPuml(
  cases: readonly UseCaseRow[],
  specs: readonly UseCaseSpec[]
): string | null {
  if (cases.length === 0) return null;
  const actors = [...new Set(cases.map((c) => c.actor).filter(Boolean))].sort();
  const out = [
    "' Generated by specgate from docs/specs/use-cases.md and docs/specs/use-cases/UC-NNN.md.",
    "' Do not edit: `specgate check` rewrites it.",
    "@startuml use-cases",
    "left to right direction",
    ...actors.map((a) => `actor "${quote(a)}" as actor_${ident(a)}`),
    "rectangle System {",
    ...byId(cases).map((c) => `  usecase "${c.id} — ${quote(c.name)}" as ${ident(c.id)}`),
    "}",
    ...byId(cases)
      .filter((c) => c.actor)
      .map((c) => `actor_${ident(c.actor)} --> ${ident(c.id)}`),
    "@enduml",
  ];
  const known = new Set(cases.map((c) => c.id));
  for (const s of byId(specs.filter((x) => known.has(x.id)))) {
    const main = s.flows.find((f) => f.id === "main");
    out.push("", `@startuml ${s.id}`, `title ${s.id} — ${quote(s.name)}`, "start");
    (main?.steps ?? []).forEach((step, i) => {
      out.push(`:${quote(step)};`);
      for (const f of s.flows.filter((x) => x.id !== "main" && x.atStep === i + 1)) {
        out.push(`if (${f.id}: ${quote(f.title)}?) then (yes)`);
        for (const st of f.steps) out.push(`  :${quote(st)};`);
        out.push("  stop", "endif");
      }
    });
    out.push("stop", "@enduml");
  }
  return out.join("\n") + "\n";
}
