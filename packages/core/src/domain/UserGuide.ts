/**
 * A user guide per actor, from what was delivered (REQ-544).
 *
 * A delivered requirement already says what an actor can do (its text) and how
 * (its scenarios: given a situation, when they act, then what they see). The
 * guide is those, for one actor, in the order of the capabilities — and only
 * what was delivered, so it never documents a feature that does not exist yet.
 * Pure: requirements in, Markdown out.
 */

export const GUIDE_DIR = "docs/guide";

export interface GuideRequirement {
  readonly id: string;
  readonly title: string;
  readonly capability: string;
  readonly actor: string;
  readonly status: string;
  /** The requirement's text, without its heading or trace. */
  readonly text: string;
  readonly scenarios: ReadonlyArray<{ readonly title: string; readonly steps: readonly string[] }>;
}

const DELIVERED = new Set(["Implemented", "Verified", "Released"]);

/** `Fleet Manager` → `fleet-manager`. */
export function actorSlug(actor: string): string {
  return (
    actor
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "actor"
  );
}

/** Every actor a delivered requirement names, sorted. */
export function deliveredActors(reqs: readonly GuideRequirement[]): string[] {
  return [
    ...new Set(reqs.filter((r) => DELIVERED.has(r.status) && r.actor).map((r) => r.actor)),
  ].sort();
}

/** `GIVEN a shipped order` → `Given a shipped order`. */
const step = (s: string) =>
  s.replace(/^(GIVEN|WHEN|THEN|AND|BUT)\b/i, (k) => k[0] + k.slice(1).toLowerCase());

/** The guide for one actor: a section per delivered requirement, by capability then id. */
export function renderGuide(actor: string, reqs: readonly GuideRequirement[]): string {
  const mine = reqs
    .filter((r) => DELIVERED.has(r.status) && r.actor.toLowerCase() === actor.toLowerCase())
    .sort(
      (a, b) =>
        a.capability.localeCompare(b.capability) ||
        a.id.localeCompare(b.id, undefined, { numeric: true })
    );
  const out = [
    `# User guide — ${actor}`,
    "",
    `<!-- Generated by \`specgate guide\` from the delivered requirements whose actor is ${actor}. -->`,
    "",
  ];
  if (mine.length === 0) {
    out.push(`Nothing is delivered for ${actor} yet.`, "");
    return out.join("\n");
  }
  let capability = "";
  for (const r of mine) {
    if (r.capability !== capability) {
      capability = r.capability;
      out.push(`## ${capability}`, "");
    }
    out.push(`### ${r.title || r.id}`, "", `_${r.id}_`, "");
    if (r.text) out.push(r.text.trim(), "");
    for (const s of r.scenarios) {
      out.push(`**${s.title}**`, "");
      s.steps.forEach((x, i) => out.push(`${i + 1}. ${step(x)}`));
      out.push("");
    }
  }
  return out.join("\n");
}
