/**
 * `docs/specs/stack.md`: the layers a project is built from and the commands
 * that build and test it (REQ-548).
 *
 * The agent, the gate and a new person all need the same three answers —
 * which technology holds each layer, how it builds, how it tests — and they
 * were scattered across `harness.config.yaml`, the README and the build files.
 * `specgate stack` writes them down from the evidence on disk, and the harness
 * and `check` take a command from here when the configuration sets none.
 *
 * Regenerating keeps a command a person edited: the layers are detected, the
 * commands are a team's to correct. Rendering is deterministic, so a second
 * run on an unchanged project writes the same bytes. Pure: text in, text out.
 */

export const STACK_FILE = "docs/specs/stack.md";

export const LAYERS = ["migration", "persistence", "service", "api", "ui", "end-to-end"] as const;
export type Layer = (typeof LAYERS)[number];

export const STACK_COMMANDS = ["build", "test", "affected-test", "end-to-end"] as const;
export type StackCommand = (typeof STACK_COMMANDS)[number];

export interface LayerFact {
  readonly layer: Layer;
  readonly technology: string;
  /** The file, dependency or folder it was detected from. */
  readonly evidence: string;
}

const cell = (v: string) => v.replace(/\|/g, "\\|");
const code = (v: string) => (v ? `\`${v}\`` : "-");

/** The file, every layer in a fixed order, every command in a fixed order. */
export function renderStack(
  layers: readonly LayerFact[],
  commands: Readonly<Partial<Record<StackCommand, string>>>
): string {
  const sorted = [...layers].sort(
    (a, b) =>
      LAYERS.indexOf(a.layer) - LAYERS.indexOf(b.layer) || a.technology.localeCompare(b.technology)
  );
  return [
    "# Stack",
    "",
    "Generated by `specgate stack` from the evidence named below. Run it again when",
    "the stack changes. A command you correct here is kept; the harness and",
    "`specgate check` use one when `harness.config.yaml` sets none.",
    "",
    "## Layers",
    "",
    "| Layer | Technology | Evidence |",
    "| --- | --- | --- |",
    ...(sorted.length
      ? sorted.map((l) => `| ${l.layer} | ${cell(l.technology)} | ${cell(l.evidence)} |`)
      : ["| - | nothing detected | - |"]),
    "",
    "## Commands",
    "",
    "| Command | Run |",
    "| --- | --- |",
    ...STACK_COMMANDS.map((c) => `| ${c} | ${code(commands[c] || "")} |`),
    "",
  ].join("\n");
}

/** The commands a stack file states; a `-` is no command. */
export function stackCommands(md: string | null): Partial<Record<StackCommand, string>> {
  const out: Partial<Record<StackCommand, string>> = {};
  if (!md) return out;
  const at = md.indexOf("## Commands");
  if (at === -1) return out;
  for (const line of md.slice(at).split(/\r?\n/)) {
    const m = /^\|\s*([a-z-]+)\s*\|\s*(.*?)\s*\|\s*$/.exec(line);
    if (!m) continue;
    const name = m[1] as StackCommand;
    if (!STACK_COMMANDS.includes(name)) continue;
    const run = m[2].replace(/^`|`$/g, "").replace(/\\\|/g, "|").trim();
    if (run && run !== "-") out[name] = run;
  }
  return out;
}

/** Detected commands, with every command the existing file states kept over them. */
export function mergeCommands(
  detected: Readonly<Partial<Record<StackCommand, string>>>,
  existing: string | null
): Partial<Record<StackCommand, string>> {
  return { ...detected, ...stackCommands(existing) };
}
