import * as readline from "node:readline/promises";

const SLUG_RE = /^[a-z0-9][a-z0-9-]*$/;

export function slugify(name: string) {
  const slug = String(name || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "my-spec-driven-app";
}

/** One question the wizard asks, and the variable its answer fills. */
export interface WizardField {
  key: string;
  question: string;
  /** The default, from the answers given so far. */
  def: (answers: Record<string, string>) => string;
  choices?: string[];
  /** An error message, or null when the value is acceptable. */
  validate?: (value: string) => string | null;
}

export const WIZARD_FIELDS: WizardField[] = [
  {
    key: "PROJECT_NAME",
    question: "Project name",
    def: () => "My Spec-Driven App",
  },
  {
    key: "PROJECT_SLUG",
    question: "Project slug",
    def: (answers) => slugify(answers.PROJECT_NAME),
    validate: (value: string) =>
      SLUG_RE.test(value)
        ? null
        : "Use lowercase letters, numbers, and dashes (example: my-project).",
  },
  {
    key: "PROJECT_TYPE",
    question: "Project type",
    choices: ["backend", "frontend", "mobile"],
    def: () => "backend",
  },
  {
    key: "DOMAIN",
    question: "Business domain (e.g. parking operations)",
    def: () => "general",
  },
  {
    key: "STACK",
    question: "Tech stack",
    def: () => "Java 21, Spring Boot 3.x, PostgreSQL",
  },
  {
    key: "API_STYLE",
    question: "API style",
    def: () => "REST with DTO boundaries",
  },
  {
    key: "TESTING",
    question: "Testing toolchain",
    def: () => "JUnit 5, Testcontainers, Cucumber",
  },
  {
    key: "MODULES",
    question: "Optional modules (auth,dashboard,billing — empty for none)",
    def: () => "",
  },
];

export function validateAnswer(field: WizardField, value: string): string | null {
  if (field.choices && !field.choices.includes(value)) {
    return `Choose one of: ${field.choices.join(", ")}.`;
  }
  if (field.validate) {
    return field.validate(value);
  }
  return null;
}

export function defaultAnswers(): Record<string, string> {
  const answers: Record<string, string> = {};
  for (const field of WIZARD_FIELDS) {
    answers[field.key] = field.def(answers);
  }
  return answers;
}

function yamlScalar(value: string) {
  return /[:#'"{}[\]&*!|>%@`]/.test(value) ? JSON.stringify(value) : value;
}

export function renderConfigYaml(answers: Record<string, unknown>): string {
  const lines = [
    "# Generated by `specgate init` (interactive wizard).",
    "# Reproduce this project with:",
    "#   specgate init --config project.yaml --out <parent-dir>",
  ];
  for (const field of WIZARD_FIELDS) {
    const value = answers[field.key];
    if (value === undefined || value === "") continue;
    lines.push(`${field.key}: ${yamlScalar(String(value))}`);
  }
  return lines.join("\n") + "\n";
}

export interface WizardIo {
  input?: NodeJS.ReadableStream;
  output?: NodeJS.WritableStream;
  question?: (prompt: string) => Promise<string>;
}

export async function runInitWizard(io?: WizardIo) {
  const output = (io && io.output) || process.stdout;
  let question: (prompt: string) => Promise<string>;
  let close = () => {};
  if (io && io.question) {
    question = io.question;
  } else {
    const rl = readline.createInterface({ input: (io && io.input) || process.stdin, output });
    question = (prompt) => rl.question(prompt);
    close = () => rl.close();
  }
  const answers: Record<string, string> = {};
  try {
    for (const field of WIZARD_FIELDS) {
      const def = field.def(answers);
      const choicesHint = field.choices ? ` (${field.choices.join("/")})` : "";
      const defHint = def === "" ? "none" : def;
      for (;;) {
        const raw = (await question(`${field.question}${choicesHint} [${defHint}]: `)).trim();
        const value = raw === "" ? def : raw;
        const error = validateAnswer(field, value);
        if (error === null) {
          answers[field.key] = value;
          break;
        }
        output.write(`✖ ${error}\n`);
      }
    }
  } finally {
    close();
  }
  return answers;
}
