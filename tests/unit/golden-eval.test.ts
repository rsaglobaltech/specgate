const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const ROOT_DIR = require("node:path").resolve(
  __dirname.split(/[\\/]tests(?:[\\/]|$)/)[0].replace(/[\\/]dist$/, "")
);
const CLI_PATH = path.join(ROOT_DIR, "bin", "specgate.js");

function cli(...args) {
  return spawnSync(process.execPath, [CLI_PATH, ...args], {
    encoding: "utf8",
    env: { ...process.env, NO_COLOR: "1" },
  });
}

const PACK = `schema_version: "1.3.0"
metadata:
  name: "Golden test"
  version: "0.1.0"
  language: "en"
  project_type: "backend"
variables:
  required:
    - PROJECT_NAME
requirements:
  - id: REQ-101
    title: "Clock in inside the geofence"
    priority: Must
    description: "Covered by a use case."
    status: Draft
  - id: REQ-102
    title: "A punch is confirmed within 2 seconds"
    priority: Must
    description: "Covered only by a scenario."
    status: Draft
use_cases:
  - id: UC-101
    name: Clock In
    actor: Worker
    requirement: REQ-101
outputs:
  files: []
rules:
  traceability:
    target: "docs/specs/traceability.md"
    include_existing_rows: true
    default_status: Draft
scenarios:
  - id: "SCN-101"
    requirement_id: REQ-102
    use_case: UC-101
    target: "features/golden/fast.feature"
    template: "templates/fast.feature.tpl"
    feature: "A punch is fast"
    scenario: "A punch is confirmed within 2 seconds"
    status: "Draft"
`;

test("a requirement referenced only by a scenario counts as referenced", () => {
  // The lint read `scenario.requirement`; the schema names it `requirement_id`,
  // so every scenario was invisible and --strict failed a correct pack.
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "specgate-golden-"));
  try {
    const dir = path.join(root, "golden", "backend");
    fs.mkdirSync(path.join(dir, "templates"), { recursive: true });
    fs.writeFileSync(path.join(dir, "pack.yaml"), PACK);
    fs.writeFileSync(
      path.join(dir, "templates", "fast.feature.tpl"),
      "Feature: A punch is fast\n\n  Scenario: A punch is confirmed within 2 seconds\n    Given a worker\n    When they clock in\n    Then it is confirmed in under 2 seconds\n"
    );
    const r = cli("pack", "lint", "--pack-root", root, "--pack", "golden/backend");
    assert.doesNotMatch(r.stdout + r.stderr, /REQ-102 is not referenced/, r.stdout + r.stderr);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("the YAML reader takes what YAML libraries write", () => {
  // PyYAML's defaults — indentless sequences and long strings folded over
  // several lines — failed with "Unexpected YAML token", so a pack generated by
  // a script did not load at all.
  const { parseYamlLite } = require("../../packages/core/src/domain/YamlLite");
  const doc = parseYamlLite(
    [
      "variables:",
      "  required:",
      "  - PROJECT_NAME",
      "  - DOMAIN",
      "requirements:",
      "- id: REQ-101",
      "  description: '[functional] A worker can clock in only when the device''s location",
      "    fix lies inside the geofence: 100 m by default.'",
      "  note: A plain description that a YAML emitter",
      "    folded onto a second line at 10:30",
      "  status: Draft",
    ].join("\n")
  );
  assert.deepEqual(doc.variables, { required: ["PROJECT_NAME", "DOMAIN"] });
  const req = doc.requirements[0];
  assert.equal(
    req.description,
    "[functional] A worker can clock in only when the device's location fix lies inside the geofence: 100 m by default."
  );
  assert.equal(
    req.note,
    "A plain description that a YAML emitter folded onto a second line at 10:30"
  );
  assert.equal(req.status, "Draft");
});

test("a trade term is not a vague step; a verdict is", () => {
  const { analyseGherkinSource } = require("../../packages/core/src/domain/GherkinQuality");
  const feature = (then) =>
    `Feature: T\n\n  Scenario: Tag work stays tag work\n    Given an email about the tag work on level 2\n    When the user asks for an explanation\n    Then ${then}\n`;
  const codes = (src) => analyseGherkinSource(src, "t.feature").map((f) => f.code);
  assert.ok(
    !codes(feature('the explanation says "tag work (trabajo extra)"')).includes("vague_step")
  );
  assert.ok(codes(feature("it works")).includes("vague_step"));
});

test("a requirement may have several scenarios; a repeat with no scenario is still refused", () => {
  // A pack expanded REQ-101 with SCN-101 and SCN-102 into two rows, and the
  // gate called it a duplicate: no requirement could have two scenarios.
  const {
    ValidateProjectUseCase,
  } = require("../../packages/core/src/application/ValidateProjectUseCase");
  const head =
    "<!-- specgate:derived — Do not edit by hand. -->\n\n" +
    "| Requirement | Scenario ID | Feature file | Use Case | Command/Query | Aggregate | Event | Technical artifact | Test artifact | Status |\n" +
    "|---|---|---|---|---|---|---|---|---|---|\n";
  const row = (req, scn) =>
    `| ${req} | ${scn} | \`f.feature\` | - | - | - | - | - | TBD | Draft |\n`;
  const codes = (table) =>
    new ValidateProjectUseCase({}).checkMatrix(head + table, {}).report.findings.map((f) => f.code);
  assert.ok(
    !codes(row("REQ-101", "SCN-101") + row("REQ-101", "SCN-102")).includes(
      "duplicate_requirement_id"
    )
  );
  assert.ok(
    codes(row("REQ-101", "SCN-101") + row("REQ-101", "-")).includes("duplicate_requirement_id")
  );
  assert.ok(
    codes(row("REQ-101", "SCN-101") + row("REQ-101", "SCN-101")).includes("duplicate_scenario_id")
  );
});

test("a pack template that already carries its tags expands without an error", () => {
  const { hasScenario, tagScenario } = require("../../packages/core/src/domain/GherkinTags");
  const src =
    "Feature: F\n\n  @REQ-101 @SCN-101\n  Scenario: A clock in is accepted\n    Given a\n    When b\n    Then c\n";
  assert.equal(tagScenario(src, "A clock in is accepted", ["@REQ-101", "@SCN-101"]), src);
  assert.equal(hasScenario(src, "A clock in is accepted"), true);
  assert.equal(hasScenario(src, "Something else"), false);
});

test("a pack keeps a generated matrix generated, and the harness sees its prose and every scenario", () => {
  // Installing a pack turned the project back into a hand-kept matrix, wrote
  // placeholder sections into spec.md, linked no scenario to capability
  // requirements, and gave the agent "no text — stop" for every one of them;
  // a requirement with two scenarios was run twice.
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "specgate-golden-pack-"));
  try {
    const packDir = path.join(root, "packs", "gold", "backend");
    fs.mkdirSync(path.join(packDir, "templates", "features"), { recursive: true });
    fs.writeFileSync(
      path.join(packDir, "pack.yaml"),
      PACK.replace(
        "outputs:\n  files: []",
        'outputs:\n  files:\n    - target: "docs/specs/capabilities/gold/spec.md"\n      template: "templates/capability.md.tpl"'
      )
        .replace("templates/fast.feature.tpl", "templates/features/fast.feature.tpl")
        .replace(
          "scenarios:\n",
          'scenarios:\n  - id: "SCN-100"\n    requirement_id: REQ-102\n    target: "features/golden/slow.feature"\n    template: "templates/features/slow.feature.tpl"\n    feature: "A punch is never slow"\n    scenario: "A punch is never slow"\n    status: "Draft"\n'
        )
    );
    fs.writeFileSync(
      path.join(packDir, "templates", "capability.md.tpl"),
      "# Capability — Gold\n\n### Requirement: REQ-101 — Clock in inside the geofence\n\nA worker MUST clock in only inside the geofence.\n\n### Requirement: REQ-102 — A punch is confirmed within 2 seconds\n\nA punch MUST be confirmed in under 2 seconds.\n"
    );
    const feature = (name) =>
      `Feature: ${name}\n\n  Scenario: ${name}\n    Given a worker at the jobsite\n    When they clock in\n    Then the confirmation shows in 2 seconds\n`;
    fs.writeFileSync(
      path.join(packDir, "templates", "features", "fast.feature.tpl"),
      feature("A punch is confirmed within 2 seconds")
    );
    fs.writeFileSync(
      path.join(packDir, "templates", "features", "slow.feature.tpl"),
      feature("A punch is never slow")
    );

    const dir = path.join(root, "app");
    fs.mkdirSync(path.join(dir, "lib"), { recursive: true });
    fs.writeFileSync(path.join(dir, "package.json"), '{"name":"app","version":"1.0.0"}');
    fs.writeFileSync(path.join(dir, "lib", "index.js"), "module.exports = {};\n");
    assert.equal(cli("adopt", "--project-dir", dir, "--no-capabilities").status, 0);

    const add = cli(
      "specops",
      "add",
      "--pack-root",
      path.join(root, "packs"),
      "--pack",
      "gold/backend",
      "--var",
      "PROJECT_NAME=App",
      "--project-dir",
      dir
    );
    assert.equal(add.status, 0, add.stdout + add.stderr);
    const matrix = fs.readFileSync(path.join(dir, "docs/specs/traceability.md"), "utf8");
    assert.match(matrix, /specgate:derived/, "the matrix stays generated");
    assert.equal((matrix.match(/^\| REQ-102 \|/gm) || []).length, 2, "a row per scenario");
    assert.doesNotMatch(fs.readFileSync(path.join(dir, "spec.md"), "utf8"), /## REQ-10[12]/);
    const check = cli("check", dir);
    assert.equal(check.status, 0, check.stdout + check.stderr);

    const prompt = cli("harness", "prompt", "REQ-102", "--project-dir", dir).stdout;
    assert.equal(
      (prompt.match(/^# Implement REQ-102/gm) || []).length,
      1,
      "one run per requirement"
    );
    assert.match(prompt, /MUST be confirmed in under 2 seconds/);
    assert.match(prompt, /A punch is never slow/);
    assert.match(prompt, /A punch is confirmed within 2 seconds/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
